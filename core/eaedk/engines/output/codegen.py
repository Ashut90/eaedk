def render_main_c(data: dict) -> str:
    fam = family_of(data["soc"]["name"] if data["soc"] else None,
                    data["soc"]["arch"] if data["soc"] else None)
    return {"stm32f1": _stm32f1, "stm32f4": _stm32f4}.get(fam, _skeleton)(data)


def render_start_here(data: dict) -> str:
    """Plain-language on-ramp for someone who has never seen a CMakeLists."""
    name = data["board_name"]
    path = data.get("learning_path", [])
    next_titles = " → ".join(s["title"] for s in path[:3]) if path else "Blink → UART → a sensor"
    fam = family_of(data["soc"]["name"] if data["soc"] else None, None)
    working = fam in ("stm32f1", "stm32f4")
    main_note = ("`src/main.c` is a **working** blink + UART program — every non-obvious line has "
                 "a comment explaining it." if working else
                 "`src/main.c` is a **skeleton** with TODOs — fill in your MCU's register init "
                 "(see the comments).")
    return f"""# START HERE — {name}

You asked EAEDK for a starting point. Here's what's in this folder and what to do, in order.

## What these files are
- **`src/main.c`** — your program. {main_note}
- **`linker/memory.ld`** — tells the compiler where your code (flash) and data (RAM) live on
  this exact chip. EAEDK filled it in from {name}'s verified memory map.
- **`cmake/toolchain.cmake`** — tells CMake to use the *cross-compiler* for this chip
  (`arm-none-eabi-gcc`), not your PC's compiler.
- **`CMakeLists.txt`** — the build recipe. You rarely edit this to start.
- **`FLASH.md`** — how to copy the built program onto the board.
- **`BRINGUP_CHECKLIST.md`** — everything EAEDK checked, and what's still missing.

## Build it
```bash
cmake -B build -DCMAKE_TOOLCHAIN_FILE=cmake/toolchain.cmake
cmake --build build
```
If that fails, run `eaedk toolchain validate` — it tells you in plain language what tool is
missing and how to install it.

## What to change first
1. Confirm the **LED pin** in `src/main.c` matches your board's schematic (it's commented).
2. Build, flash (see `FLASH.md`), and watch the LED. That's the whole loop working.
3. Open a serial terminal at **115200 8N1** to see the "Hello" message.

## What to try next
Your learning path: **{next_titles}**.
Run `eaedk mentor --board "{name}"` any time to see the full path and the *why* behind each step.
"""
